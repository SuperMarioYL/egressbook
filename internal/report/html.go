type kv struct {
	Key   string
	Value int64
}

type pageData struct {
	GeneratedAt string
	Source      string
	ItemCount   int
	Signature   *model.Signature
	Harnesses   []model.Coverage
	Providers   []kv
	Kinds       []kv
	Items       []itemRow
}

type itemRow struct {
	Timestamp    string
	Harness      string
	Kind         string
	DestProvider string
	Bytes        int64
	Evidence     string
}

// HTML renders the self-contained disclosure report to w.
func HTML(w io.Writer, l *model.Ledger) error {
	tmpl, err := template.New("report").Parse(htmlTemplate)
	if err != nil {
		return err
	}
	data := pageData{
		GeneratedAt: l.GeneratedAt.Format("2006-01-02 15:04 MST"),
		Source:      l.Source,
		ItemCount:   len(l.Items),
		Signature:   l.Signature,
		Harnesses:   l.Harnesses,
	}
	for k, v := range l.TotalsByProvider() {
		data.Providers = append(data.Providers, kv{k, v})
	}
	sort.Slice(data.Providers, func(i, j int) bool {
		if data.Providers[i].Value != data.Providers[j].Value {
			return data.Providers[i].Value > data.Providers[j].Value
		}
		return data.Providers[i].Key < data.Providers[j].Key
	})
	for _, k := range model.AllItemKinds {
		if v, ok := l.TotalsByKind()[k]; ok {
			data.Kinds = append(data.Kinds, kv{string(k), v})
		}
	}
	items := append([]model.EgressItem{}, l.Items...)
	sort.Slice(items, func(i, j int) bool { return items[i].Timestamp.After(items[j].Timestamp) })
	for _, it := range items {
		data.Items = append(data.Items, itemRow{
			Timestamp:    it.Timestamp.Format("2006-01-02 15:04"),
			Harness:      it.Harness,
			Kind:         string(it.Kind),
			DestProvider: it.DestProvider,
			Bytes:        it.Bytes,
			Evidence:     shortFile(it.Evidence.File) + ":" + itoa(it.Evidence.Line),
		})
	}
	return tmpl.Execute(w, data)
}

// shortFile abbreviates a log path for the report while keeping the file name:
// the evidence locator must stay identifiable, so the parent directory and the
// file are kept and longer paths are prefixed with "…/".
func shortFile(p string) string {
	if i := lastSlash(p); i >= 0 {
		if j := lastSlash(p[:i]); j >= 0 {
			return "…/" + p[j+1:]
		}
	}
	return p
}

func lastSlash(p string) int {
	for i := len(p) - 1; i >= 0; i-- {
		if p[i] == '/' {
			return i
		}
	}
	return -1
}

func itoa(n int) string {
	if n == 0 {
		return "0"
	}
	neg := n < 0
	if neg {
		n = -n
	}
	var b [20]byte
	i := len(b)
	for n > 0 {
		i--
		b[i] = byte('0' + n%10)
		n /= 10
	}
	if neg {
		i--
		b[i] = '-'
	}
	return string(b[i:])
}
